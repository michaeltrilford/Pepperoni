import docgen from "react-docgen-typescript";
import fs from "node:fs";
import path from "node:path";
import ts from "typescript";

const projectRoot = process.cwd();
const srcDir = path.join(projectRoot, "src");
const componentsDir = path.join(srcDir, "components");
const knowledgeDir = path.join(srcDir, "knowledge");
const fragmentsDir = path.join(knowledgeDir, "fragments");
const skillDir = path.join(knowledgeDir, "skills", "pepperoni-components");
const publicKnowledgeDir = path.join(projectRoot, "public", "knowledge");
const distDir = path.join(projectRoot, "dist");
const distKnowledgeDir = path.join(distDir, "knowledge");

function findComponentFiles(dir) {
  let results = [];
  if (!fs.existsSync(dir)) return results;
  
  const list = fs.readdirSync(dir);
  list.forEach((file) => {
    const filePath = path.join(dir, file);
    const stat = fs.statSync(filePath);
    if (stat && stat.isDirectory()) {
      if (file !== "node_modules" && file !== "test" && file !== "tokens") {
        results = results.concat(findComponentFiles(filePath));
      }
    } else if (file.endsWith(".tsx") && !file.endsWith(".test.tsx") && !file.endsWith(".stories.tsx")) {
      results.push(filePath);
    }
  });
  return results;
}

function loadDataTs(filePath) {
  if (!fs.existsSync(filePath)) return null;
  const content = fs.readFileSync(filePath, "utf8");
  const jsContent = ts.transpileModule(content, {
    compilerOptions: {
      module: ts.ModuleKind.CommonJS,
      target: ts.ScriptTarget.ES2022
    },
    fileName: filePath
  }).outputText;

  try {
    const module = { exports: {} };
    const evaluate = new Function("exports", "module", "require", jsContent);
    evaluate(module.exports, module, (specifier) => {
      throw new Error(`Runtime imports are not supported in component metadata: ${specifier}`);
    });
    return module.exports;
  } catch (err) {
    console.warn(`Could not parse ${filePath}:`, err.message);
    return null;
  }
}

function loadFragments() {
  if (!fs.existsSync(fragmentsDir)) return [];

  const fragments = fs.readdirSync(fragmentsDir)
    .filter((file) => file.endsWith(".json"))
    .sort()
    .map((file) => JSON.parse(fs.readFileSync(path.join(fragmentsDir, file), "utf8")));
  const ids = new Set();

  for (const fragment of fragments) {
    for (const field of ["id", "title", "description", "useWhen", "components", "rules", "example"]) {
      if (fragment[field] === undefined) {
        throw new Error(`Knowledge fragment ${fragment.id || "<unknown>"}: missing ${field}`);
      }
    }
    if (ids.has(fragment.id)) {
      throw new Error(`Duplicate knowledge fragment id: ${fragment.id}`);
    }
    ids.add(fragment.id);
  }

  return fragments;
}

function buildKnowledgeSkill(manifest) {
  const componentNames = new Set(manifest.fragments.flatMap((fragment) => fragment.components));
  const componentReference = manifest.components
    .filter((component) => componentNames.has(component.displayName))
    .map((component) => {
      const props = Object.entries(component.api.props)
        .map(([name, prop]) => `- \`${name}\`: ${prop.description} Type: \`${prop.type}\`${prop.defaultValue === undefined ? "" : `; default: \`${prop.defaultValue}\``}`)
        .join("\n");
      return `### ${component.displayName}\n\n${component.api.element} extending ${component.api.inherits || "native attributes"}.\n\n${props}`;
    })
    .join("\n\n");
  const fragmentReference = manifest.fragments
    .map((fragment) => `### ${fragment.title}\n\n${fragment.description}\n\n**Use when:** ${fragment.useWhen}\n\n**Rules**\n\n${fragment.rules.map((rule) => `- ${rule}`).join("\n")}\n\n**JSON composition**\n\n\`\`\`json\n${JSON.stringify(fragment.example, null, 2)}\n\`\`\``)
    .join("\n\n");
  const skill = `---
name: pepperoni-components
description: Compose and review Pepperoni React interfaces using verified component contracts and established composition use cases. Use when selecting Pepperoni components, implementing cross-component patterns, or adapting fragments such as editable TextInput controls inside Table cells.
---

<!-- DO NOT EDIT THIS FILE MANUALLY -->
<!-- Generated by scripts/generate-manifest.js from the component manifest and src/knowledge/fragments. -->

# Pepperoni Components

Compose Pepperoni interfaces from established use cases while preserving component ownership, native semantics, accessibility, and public API boundaries.

## Workflow

1. Select the fragment closest to the requested use case.
2. Confirm every referenced component and prop against the component API reference in this file.
3. Adapt content and native structure while preserving the fragment's rules and ownership boundaries.
4. Convert its \`{ type, props, children }\` JSON tree to React JSX when implementation is requested.
5. Preserve native semantics, accessible labels, inherited sizing, and documented usage props.

## Boundaries

- Do not invent component props, variants, sizes, or composition attributes.
- Treat fragments as adaptable patterns, not fixed content templates.
- Do not author internal data attributes such as \`data-table-cell-control\`; components emit them from their public usage props.
- Let the parent own layout and the child own interaction and accessibility.
- Use the wider knowledge bundle only when guidance beyond this portable snapshot is required and available.

## Component API Reference

${componentReference}

## Composition Fragments

${fragmentReference}
`;

  fs.rmSync(skillDir, { recursive: true, force: true });
  fs.mkdirSync(skillDir, { recursive: true });
  fs.writeFileSync(path.join(skillDir, "SKILL.md"), skill, "utf8");
}

const componentFiles = findComponentFiles(componentsDir);

const parser = docgen.withCustomConfig(path.join(projectRoot, "tsconfig.json"), {
  savePropValueAsString: true,
  shouldExtractLiteralValuesFromEnum: true,
  shouldRemoveUndefinedFromOptional: true,
  propFilter: (prop) => (prop.parent ? !prop.parent.fileName.includes("node_modules") : true)
});

let docs = [];
if (componentFiles.length > 0) {
  docs = parser.parse(componentFiles);
}

docs = docs.map((doc) => {
  const dir = path.dirname(doc.filePath);
  const docTsPath = path.join(dir, "Doc.ts");
  const apiTsPath = path.join(dir, "Api.ts");
  const docData = loadDataTs(docTsPath);
  const apiData = loadDataTs(apiTsPath);
  if (docData) {
    const componentDocs = docData.muiDocs?.[doc.displayName];
    if (componentDocs) {
      doc.guidelines = componentDocs;
    }
  }
  if (apiData?.api) {
    doc.api = apiData.api;
  }
  return doc;
});

const metadataErrors = [];

function validateCustomRenderSources() {
  for (const file of fs.readdirSync(componentsDir, { recursive: true })) {
    if (typeof file !== "string" || !file.endsWith(".stories.tsx")) continue;

    const filePath = path.join(componentsDir, file);
    const sourceFile = ts.createSourceFile(filePath, fs.readFileSync(filePath, "utf8"), ts.ScriptTarget.Latest, true, ts.ScriptKind.TSX);

    for (const statement of sourceFile.statements) {
      if (!ts.isVariableStatement(statement)) continue;
      for (const declaration of statement.declarationList.declarations) {
        if (!declaration.initializer || !ts.isObjectLiteralExpression(declaration.initializer)) continue;
        const hasCustomRender = declaration.initializer.properties.some((property) => (
          ts.isPropertyAssignment(property) && property.name.getText(sourceFile) === "render"
        ));
        if (!hasCustomRender) continue;

        const metadataSpread = declaration.initializer.properties.find((property) => (
          ts.isSpreadAssignment(property)
          && ts.isCallExpression(property.expression)
          && property.expression.expression.getText(sourceFile) === "getStoryMetaFromManifest"
        ));
        const storyName = declaration.name.getText(sourceFile);
        if (!metadataSpread || !ts.isSpreadAssignment(metadataSpread) || !ts.isCallExpression(metadataSpread.expression)) {
          metadataErrors.push(`${file}:${storyName}: custom render is missing getStoryMetaFromManifest metadata`);
          continue;
        }

        const [componentArg, storyArg] = metadataSpread.expression.arguments;
        if (!ts.isStringLiteral(componentArg) || !ts.isStringLiteral(storyArg)) continue;
        const component = docs.find((doc) => doc.displayName === componentArg.text);
        const story = component?.guidelines?.stories?.items?.find((item) => item.key === storyArg.text);
        if (!story?.source) {
          metadataErrors.push(`${file}:${storyName}: custom render story ${componentArg.text}.${storyArg.text} is missing Doc.ts source`);
        }
      }
    }
  }
}

validateCustomRenderSources();

for (const doc of docs) {
  if (!doc.guidelines) metadataErrors.push(`${doc.displayName}: missing Doc.ts guidelines`);
  if (!doc.api) metadataErrors.push(`${doc.displayName}: missing Api.ts metadata`);
  if (doc.api && doc.api.name !== doc.displayName) {
    metadataErrors.push(`${doc.displayName}: Api.ts name is ${doc.api.name}`);
  }

  for (const propName of Object.keys(doc.props || {})) {
    if (doc.api && !doc.api.props?.[propName]) {
      metadataErrors.push(`${doc.displayName}.${propName}: missing Api.ts prop metadata`);
    }
  }
}

if (metadataErrors.length > 0) {
  throw new Error(`Component metadata validation failed:\n${metadataErrors.join("\n")}`);
}

if (!fs.existsSync(distDir)) {
  fs.mkdirSync(distDir, { recursive: true });
}
if (!fs.existsSync(knowledgeDir)) {
  fs.mkdirSync(knowledgeDir, { recursive: true });
}

const knowledgeOutputPath = path.join(knowledgeDir, "component-manifest.json");
const manifest = {
  schemaVersion: "1.0.0",
  components: docs,
  fragments: loadFragments()
};
const manifestJson = `${JSON.stringify(manifest, null, 2)}\n`;

fs.writeFileSync(knowledgeOutputPath, manifestJson, "utf8");
buildKnowledgeSkill(manifest);

function mirrorKnowledge(destination) {
  fs.rmSync(destination, { recursive: true, force: true });
  fs.cpSync(knowledgeDir, destination, {
    recursive: true,
    filter: (source) => {
      const relativePath = path.relative(knowledgeDir, source);
      return relativePath !== "fragments" && !relativePath.startsWith(`fragments${path.sep}`);
    }
  });
}

mirrorKnowledge(publicKnowledgeDir);
mirrorKnowledge(distKnowledgeDir);

const fragmentLabel = manifest.fragments.length === 1 ? "fragment" : "fragments";
console.log(`✓ Knowledge successfully generated (${docs.length} components, ${manifest.fragments.length} ${fragmentLabel})`);
console.log(`  Source: ${knowledgeOutputPath}`);
console.log(`  Public: ${publicKnowledgeDir}`);
console.log(`  Package: ${distKnowledgeDir}`);
